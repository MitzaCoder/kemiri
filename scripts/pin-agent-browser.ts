import { writeFile } from "node:fs/promises";

export const agentBrowserPlatforms = ["linux-x64-gnu", "linux-arm64-gnu", "linux-x64-musl", "linux-arm64-musl", "darwin-arm64", "darwin-x64"] as const;

export function parseAgentBrowserMetadata(metadata: unknown, packageName: string, version: string) {
	const entry = metadata as { name?: string; version?: string; dist?: { tarball?: string; integrity?: string } } | null;
	if (entry?.name !== packageName || entry.version !== version ||
		!entry.dist?.tarball?.startsWith("https://registry.npmjs.org/") ||
		!/^sha512-[A-Za-z0-9+/]{86}==$/.test(entry.dist.integrity ?? "")) {
		throw new Error(`Invalid registry metadata for ${packageName}@${version}`);
	}
	return { packageName, tarball: entry.dist.tarball, integrity: entry.dist.integrity! };
}

if (import.meta.main) {
	const version = process.argv[2];
	if (!version || !/^\d+\.\d+\.\d+(?:-[a-zA-Z0-9.-]+)?$/.test(version)) throw new Error("Usage: bun scripts/pin-agent-browser.ts <version>");
	const platforms: Record<string, ReturnType<typeof parseAgentBrowserMetadata>> = {};
	for (const platform of agentBrowserPlatforms) {
		const packageName = `@agent-browser/cli-${platform}`;
		const response = await fetch(`https://registry.npmjs.org/${packageName}/${version}`);
		if (!response.ok) throw new Error(`Registry HTTP ${response.status}`);
		platforms[platform] = parseAgentBrowserMetadata(await response.json(), packageName, version);
	}
	await writeFile(new URL("../packages/server/src/agent-browser-pin.ts", import.meta.url),
		`// Generated by bun scripts/pin-agent-browser.ts <version>. Review pin changes before release.\nexport const agentBrowserPin = ${JSON.stringify({ version, platforms }, null, "\t")} as const;\n`);
}

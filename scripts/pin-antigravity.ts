import { writeFile } from "node:fs/promises";

const platforms = ["linux_amd64", "linux_arm64", "linux_amd64_musl", "linux_arm64_musl", "darwin_amd64", "darwin_arm64"];
const manifestOrigin = "https://antigravity-cli-auto-updater-974169037036.us-central1.run.app";

if (import.meta.main) {
	const version = process.argv[2];
	if (!version || !/^\d+\.\d+\.\d+$/.test(version)) throw new Error("Usage: bun scripts/pin-antigravity.ts <version>");
	const downloads = await Promise.all(platforms.map(async platform => {
		const response = await fetch(`${manifestOrigin}/manifests/${platform}.json`, { signal: AbortSignal.timeout(30_000) });
		if (!response.ok) throw new Error(`Antigravity manifest for ${platform}: HTTP ${response.status}`);
		const entry = await response.json() as { version?: string; url?: string; sha512?: string };
		if (entry.version !== version || !entry.url?.startsWith(`https://storage.googleapis.com/antigravity-public/antigravity-cli/${version}-`) ||
			!entry.url.endsWith(".tar.gz") || !entry.sha512 || !/^[a-f0-9]{128}$/.test(entry.sha512)) {
			throw new Error(`Google's current ${platform} manifest does not describe Antigravity ${version}`);
		}
		return [platform, { url: entry.url, sha512: entry.sha512 }];
	}));
	await writeFile(new URL("../packages/server/src/antigravity-pin.ts", import.meta.url),
		`// Generated by bun scripts/pin-antigravity.ts <version>. Review pin changes before release.\nexport const antigravityPin = ${JSON.stringify({ version, platforms: Object.fromEntries(downloads) }, null, "\t")} as const;\n`);
}
